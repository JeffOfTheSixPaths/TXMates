/**
 * Returns activities tailored for ANY requested city or location.
 * Gracefully resolves Austin, San Antonio, Dallas, Boston, or dynamically
 * generates authentic activities for any arbitrary city (e.g. Seattle, Denver, Chicago).
 */
export function getActivitiesForLocation(location?: string): Activity[] {
  if (!location) return MOCK_ACTIVITIES;
  const loc = location.toLowerCase().trim();

  if (loc.includes('san antonio') || loc.includes('satx') || loc.includes('alamo') || loc.includes('river walk')) {
    return SAN_ANTONIO_ACTIVITIES;
  }
  if (loc.includes('dallas') || loc.includes('dfw') || loc.includes('deep ellum') || loc.includes('klyde warren')) {
    return DALLAS_ACTIVITIES;
  }
  if (loc.includes('boston') || loc.includes('cambridge') || loc.includes('fenway') || loc.includes('north end')) {
    return BOSTON_ACTIVITIES;
  }
  if (loc.includes('austin') || loc.includes('atx') || loc.includes('zilker') || loc.includes('barton springs')) {
    return MOCK_ACTIVITIES;
  }

  // Extract clean city name, e.g. "Chicago, IL" -> "Chicago", "Seattle" -> "Seattle"
  const cleanCity = location.replace(/\(.*?\)/g, '').split(',')[0]?.trim();
  if (cleanCity && cleanCity.length > 1) {
    return generateDynamicCityActivities(cleanCity);
  }

  return MOCK_ACTIVITIES;
}

